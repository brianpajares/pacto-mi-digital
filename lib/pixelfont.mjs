export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Ancho en píxeles de un texto al tamaño de escala dado. */
export function textWidth(text, scale, tracking = 1) {
  return text.length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/**
 * Dibuja texto sobre un buffer RGB.
 * @param {Buffer} rgb  buffer destino (width*height*3)
 */
export function drawText(rgb, width, text, { x, y, scale, color, tracking = 1 }) {
  let cursor = x;
  for (const char of text.toUpperCase()) {
    const glyph = GLYPHS[char] ?? GLYPHS[" "];
    for (let row = 0; row < GLYPH_H; row += 1) {
      for (let col = 0; col < GLYPH_W; col += 1) {
        if (!(glyph[row] & (1 << (GLYPH_W - 1 - col)))) continue;
        for (let dy = 0; dy < scale; dy += 1) {
          for (let dx = 0; dx < scale; dx += 1) {
            const px = cursor + col * scale + dx;
            const py = y + row * scale + dy;
            const i = (py * width + px) * 3;
            if (i < 0 || i + 2 >= rgb.length) continue;
            rgb[i] = color[0];
            rgb[i + 1] = color[1];
            rgb[i + 2] = color[2];
          }
        }
      }
    }
    cursor += (GLYPH_W + tracking) * scale;
  }
}
